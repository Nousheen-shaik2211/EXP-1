from getpass import getpass
from google import genai
from google.genai import errors

try:
    api_key = getpass("Enter your Gemini API key: ").strip()

    if not api_key:
        raise ValueError("Gemini API key is missing.")

    print("API key loaded successfully.")
    print("Environment ready. Sending prompt...")

    client = genai.Client(api_key=api_key)

    prompt = "What is prompt engineering? Answer in one sentence."

    print("\nPrompt:")
    print(prompt)

    response = client.models.generate_content(
        model="gemini-3.8-flash",
        contents=prompt
    )

    print("\nResponse:")
    print(response.text)

    print("\nPrompt sent successfully.")
    print("Response received from Gemini.")

except ValueError as e:
    print("Configuration Error:", str(e))

except errors.APIError as e:
    print("Gemini API Error:", str(e).encode(
        "ascii", errors="replace"
    ).decode("ascii"))

except Exception as e:
    print("Unexpected Error:", str(e).encode(
        "ascii", errors="replace"
    ).decode("ascii"))